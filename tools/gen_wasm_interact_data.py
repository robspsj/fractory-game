#!/usr/bin/env python3
"""Generate wasm_interact_data.h — interaction CSVs embedded in the wasm build.

The web link runs with -sFILESYSTEM=0, so the model cannot read assets/*.csv at
runtime — the same reason item icons are baked by gen_wasm_svg_assets.py. This
tool embeds the data files verbatim as string literals, so the wasm runtime
parses exactly the same bytes the native build reads from disk (single source of
truth stays the CSV in assets/).

Usage: python3 tools/gen_wasm_interact_data.py <repo_root> <out_header.h>
"""
import os
import sys

# (C++ symbol, path relative to the repo root)
FILES = [
    ("FRACTORY_EMBEDDED_STATION_RECIPES", "assets/station_recipes.csv"),
]

RAW_OPEN = 'R"CSV('
RAW_CLOSE = ')CSV"'


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    root, out = sys.argv[1], sys.argv[2]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)

    lines = [
        "// Generated by tools/gen_wasm_interact_data.py — do not edit.",
        "// Data files are embedded verbatim so the wasm runtime (no filesystem)",
        "// parses the same bytes the native build reads from assets/.",
        "#pragma once",
        "",
    ]
    for symbol, rel in FILES:
        with open(os.path.join(root, rel), "r", encoding="utf-8") as f:
            text = f.read()
        if RAW_CLOSE in text:
            raise SystemExit(f"{rel}: contains the raw-string terminator {RAW_CLOSE}")
        lines.append(f"// {rel}")
        lines.append(f"static const char *{symbol} = {RAW_OPEN}")
        lines.append(text.rstrip("\n"))
        lines.append(f"{RAW_CLOSE};")
        lines.append("")

    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"gen_wasm_interact_data: wrote {out} ({len(FILES)} file(s))")


if __name__ == "__main__":
    main()
