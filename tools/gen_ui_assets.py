#!/usr/bin/env python3
"""Generate rounded-color-square UI tiles and embed them into a header.

Writes assets/ui/bg_N.svg (grid container background) and assets/ui/cell_N.svg
(inner item/empty cell) for N per-size colour families, then embeds all of them
into src/game/ui_assets.h so Skia can render them (native). Each grid's
`variation` (= its dimension) selects one of these families at render time.

Regenerate after editing the palette: python3 tools/gen_ui_assets.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, '..'))
uidir = os.path.join(root, 'assets', 'ui')
out = os.path.join(root, 'src', 'game', 'ui_assets.h')
os.makedirs(uidir, exist_ok=True)

# Per-size colour families. Index = size-1 (sizes 1..5); clamped beyond.
PALETTE = [
    # (bg fill, cell fill)  size
    ('#6B7280', '#9CA3AF'),  # 1 gray
    ('#0D9488', '#2DD4BF'),  # 2 teal
    ('#D97706', '#FBBF24'),  # 3 amber
    ('#7C3AED', '#A78BFA'),  # 4 purple
    ('#2563EB', '#60A5FA'),  # 5 blue
]


def tile_svg(fill, rx):
    # preserveAspectRatio="none" makes the tile STRETCH to fill its container.
    # Cells are laid out in a non-square NDC rect that maps to a square in pixels;
    # with the default "meet" the square viewBox would be letterboxed and then
    # pixel-scaled non-uniformly, making the visible tile depend on window aspect.
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        'preserveAspectRatio="none" viewBox="0 0 64 64">'
        '<rect x="1.5" y="1.5" width="61" height="61" rx="%d" fill="%s"/>'
        '<rect x="1.5" y="1.5" width="61" height="61" rx="%d" fill="none" '
        'stroke="#000000" stroke-opacity="0.18" stroke-width="2"/>'
        '</svg>' % (rx, fill, rx)
    )


def emit(data):
    out = []
    for i in range(0, len(data), 16):
        out.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    return '\n'.join(out)


def main():
    lines = []
    lines.append('#pragma once')
    lines.append('// GENERATED by tools/gen_ui_assets.py — do not edit by hand.')
    lines.append('// Regenerate: python3 tools/gen_ui_assets.py')
    lines.append('#include <cstddef>')
    lines.append('')
    lines.append('namespace ui {')
    lines.append('struct Svg { const unsigned char* data; std::size_t size; };')
    lines.append('')

    bg_svgs, cell_svgs = [], []
    for i, (bg, cell) in enumerate(PALETTE):
        # write the source .svg files too (the "svg on our assets" ask)
        with open(os.path.join(uidir, 'bg_%d.svg' % i), 'w') as f:
            f.write(tile_svg(bg, 16))
        with open(os.path.join(uidir, 'cell_%d.svg' % i), 'w') as f:
            f.write(tile_svg(cell, 10))

        bb = tile_svg(bg, 16).encode('utf-8')
        cb = tile_svg(cell, 10).encode('utf-8')
        lines.append('static const unsigned char bg_%d_data[] = {' % i)
        lines.append(emit(bb))
        lines.append('};')
        lines.append('')
        lines.append('static const unsigned char cell_%d_data[] = {' % i)
        lines.append(emit(cb))
        lines.append('};')
        lines.append('')
        bg_svgs.append('    {bg_%d_data, sizeof(bg_%d_data)},' % (i, i))
        cell_svgs.append('    {cell_%d_data, sizeof(cell_%d_data)},' % (i, i))

    lines.append('static const Svg bg[%d] = {' % len(PALETTE))
    lines.extend(bg_svgs)
    lines.append('};')
    lines.append('')
    lines.append('static const Svg cell[%d] = {' % len(PALETTE))
    lines.extend(cell_svgs)
    lines.append('};')
    lines.append('}  // namespace ui')
    lines.append('')
    open(out, 'w').write('\n'.join(lines))
    print('wrote %s (bg/cell families=%d)' % (out, len(PALETTE)))


if __name__ == '__main__':
    main()