#!/usr/bin/env python3
"""Regenerate src/game/chess_assets.h from assets/ChessWhite/element*.svg.

The item icons in the game are the chess-piece SVGs baked into a header so the
same bytes are available on native (web stays on vector symbols). Swap a piece
by replacing assets/ChessWhite/elementN.svg, re-run, rebuild.

Skia's SkSVGDOM ignores <style>-block CSS classes (paths default to black) and
doesn't apply opacity on the full-canvas background <rect>, so these pieces
rasterize as solid-black squares. We therefore pre-process each SVG to inline
its class colors as fill="" attributes and drop the opaque background rect.
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, '..'))
srcdir = os.path.join(root, 'assets', 'ChessWhite')
out = os.path.join(root, 'src', 'game', 'chess_assets.h')

NAMES = [f'element{i}.svg' for i in range(5)]


def transform_svg(svg: str) -> str:
    # 1) Parse the <style> block into class -> {fill, opacity} map.
    cls = {}
    style_m = re.search(r'<style>(.*?)</style>', svg, re.S | re.I)
    if style_m:
        for m in re.finditer(r'\.([\w-]+)\s*\{([^}]*)\}', style_m.group(1)):
            name, body = m.group(1), m.group(2)
            d = {}
            ft = re.search(r'fill\s*:\s*([^;]+)', body)
            if ft:
                d['fill'] = ft.group(1).strip()
            op = re.search(r'opacity\s*:\s*([^;]+)', body)
            if op:
                d['opacity'] = op.group(1).strip()
            cls[name] = d

    # 2) Drop the full-canvas background <rect> (opacity:0 canvas we don't need).
    svg = re.sub(r'<rect[^>]*width\s*=\s*"72"[^>]*height\s*=\s*"72"[^>]*\s*>',
                 '', svg, flags=re.I)
    svg = re.sub(r'<rect[^>]*height\s*=\s*"72"[^>]*width\s*=\s*"72"[^>]*\s*>',
                 '', svg, flags=re.I)

    # 3) Inline class colors onto any element carrying class="..." (fill only; a
    #    transparent opacity is handled by simply not drawing that bg rect).
    def inline(m):
        tag = m.group(0)
        cm = re.search(r'class\s*=\s*"([\w\s-]+)"', tag)
        if not cm:
            return tag
        for cname in cm.group(1).split():
            d = cls.get(cname, {})
            if 'fill' in d and not re.search(r'fill\s*=', tag):
                tag = re.sub(r'<(\w+)', r'<\1 fill="%s"' % d['fill'], tag,
                             count=1)
        return tag
    return re.sub(r'<[a-zA-Z][^>]*class\s*=\s*"[^"]*"[^>]*>', inline, svg)


def main():
    lines = []
    lines.append('#pragma once')
    lines.append('// GENERATED by tools/gen_chess_assets.py from assets/ChessWhite/*.svg — do not edit by hand.')
    lines.append('// Regenerate after swapping piece SVGs: python3 tools/gen_chess_assets.py')
    lines.append('#include <cstddef>')
    lines.append('')
    lines.append('namespace chess {')
    lines.append('struct Svg { const unsigned char* data; std::size_t size; };')
    lines.append('')
    entries = []
    for n in NAMES:
        p = os.path.join(srcdir, n)
        if not os.path.exists(p):
            sys.exit(f'error: missing {p}')
        raw = open(p, 'rb').read().decode('utf-8', 'replace')
        blob = transform_svg(raw).encode('utf-8')
        var = 'element%d_data' % int(re.match(r'element(\d)', n).group(1))
        lines.append(f'static const unsigned char {var}[] = {{')
        for i in range(0, len(blob), 16):
            lines.append('    ' + ', '.join('0x%02x' % b for b in blob[i:i+16]) + ',')
        lines.append('};')
        lines.append('')
        entries.append(f'    {{{var}, sizeof({var})}},')
    lines.append(f'static const Svg pieces[{len(entries)}] = {{')
    lines.extend(entries)
    lines.append('};')
    lines.append('}  // namespace chess')
    lines.append('')
    open(out, 'w').write('\n'.join(lines))
    nb = len('\n'.join(lines))
    print(f'wrote {out} ({nb} bytes)')


if __name__ == '__main__':
    main()