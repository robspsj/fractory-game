#pragma once
#include <vector>

// Crafting — Minecraft-style shaped recipes matched against a pattern of ITEM
// cells on the board (see docs/crafting.md).
//
// A recipe is a list of (offset, itemId) entries. Offsets are 2D cell
// coordinates (dr = down, dc = right) relative to the recipe's own origin, so
// recipes stay readable and can grow into non-rectangular / multi-layer shapes
// later without changing the format.
struct CraftEntry {
  int dr = 0;
  int dc = 0;
  int itemId = 0;
};

struct CraftingRule {
  int result = 0;
  int resultCount = 1;
  std::vector<CraftEntry> entries;
  // Bounding box of `entries` (offsets, so minDr/minDc are usually 0). Used to
  // slide the recipe over the clicked cell instead of requiring a fixed origin.
  int minDr = 0, maxDr = 0, minDc = 0, maxDc = 0;
};

// The crafting element: an item that, while HELD (dragging), turns a right-click
// into a craft attempt in the clicked area, and is spent one unit per craft.
// Ids are the rows of assets/items.csv — 3 is not generated by the random world
// (Config::numItems stays 3), so it must be crafted/reaction-made in-game.
inline constexpr int CRAFT_TOOL_ITEM = 3;
